-- ---------- ADMIN ----------
create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique,
  created_at timestamptz not null default now()
);

alter table public.admin_users enable row level security;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.admin_users a
    where a.user_id = auth.uid()
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;

drop policy if exists "admin users read own" on public.admin_users;
create policy "admin users read own" on public.admin_users
for select to authenticated
using (user_id = auth.uid());

drop policy if exists "admin users manage" on public.admin_users;
create policy "admin users manage" on public.admin_users
for all to authenticated
using (public.is_admin())
with check (public.is_admin());

