-- ---------- REALTIME ----------
-- Realtime diperlukan supaya Like/View/galeri/request bisa ikut berubah tanpa refresh.
do $$
begin
  if exists (select 1 from pg_publication where pubname='supabase_realtime') then
    if not exists (select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='photos') then
      alter publication supabase_realtime add table public.photos;
    end if;
    if not exists (select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='contact_messages') then
      alter publication supabase_realtime add table public.contact_messages;
    end if;
    if not exists (select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='profile') then
      alter publication supabase_realtime add table public.profile;
    end if;
  end if;
end $$;

