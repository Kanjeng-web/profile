-- ---------- COUNTER FUNCTIONS ----------
create or replace function public.add_like(p_photo_id bigint, p_visitor_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  inserted boolean := false;
  new_count bigint := 0;
begin
  if p_photo_id is null or p_visitor_id is null then
    raise exception 'photo_id and visitor_id are required';
  end if;

  insert into public.photo_likes(photo_id, visitor_id)
  values (p_photo_id, p_visitor_id)
  on conflict (photo_id, visitor_id) do nothing;
  inserted := found;

  update public.photos p
  set likes = (select count(*) from public.photo_likes l where l.photo_id = p_photo_id),
      updated_at = now()
  where p.id = p_photo_id
  returning likes into new_count;

  return jsonb_build_object('liked', inserted, 'likes', coalesce(new_count,0));
end;
$$;

create or replace function public.add_view(p_photo_id bigint, p_visitor_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  inserted boolean := false;
  new_count bigint := 0;
begin
  if p_photo_id is null or p_visitor_id is null then
    raise exception 'photo_id and visitor_id are required';
  end if;

  insert into public.photo_views(photo_id, visitor_id, viewed_on)
  values (p_photo_id, p_visitor_id, current_date)
  on conflict (photo_id, visitor_id, viewed_on) do nothing;
  inserted := found;

  update public.photos p
  set views = (select count(*) from public.photo_views v where v.photo_id = p_photo_id),
      updated_at = now()
  where p.id = p_photo_id
  returning views into new_count;

  return jsonb_build_object('counted', inserted, 'views', coalesce(new_count,0));
end;
$$;

create or replace function public.add_download(p_photo_id bigint, p_visitor_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  inserted boolean := false;
  new_count bigint := 0;
begin
  if p_photo_id is null or p_visitor_id is null then
    raise exception 'photo_id and visitor_id are required';
  end if;

  insert into public.photo_downloads(photo_id, visitor_id, downloaded_on)
  values (p_photo_id, p_visitor_id, current_date)
  on conflict (photo_id, visitor_id, downloaded_on) do nothing;
  inserted := found;

  update public.photos p
  set downloads = (select count(*) from public.photo_downloads d where d.photo_id = p_photo_id),
      updated_at = now()
  where p.id = p_photo_id
  returning downloads into new_count;

  return jsonb_build_object('counted', inserted, 'downloads', coalesce(new_count,0));
end;
$$;

